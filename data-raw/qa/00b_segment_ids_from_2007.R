# Run from the package root: Rscript data-raw/qa/00b_segment_ids_from_2007.R
source("data-raw/qa/helpers.R")
suppressMessages(library(dplyr))
t <- read.csv(qa_spc_csv()) %>% filter(yr>=1996) %>% mutate(id=paste(yr,om,sep="_"))
cat("om class:", class(t$om), "; ids containing '-':", sum(grepl("-", t$om)), "\n")
print(table(t$yr[grepl("-", t$om)]))
dash <- t %>% filter(grepl("-", om)); print(table(dash$sg, dash$ns))
dash$base <- sub("-[0-9]+$","",dash$om)
print(head(t %>% filter(om %in% c("0703282040","0703282040-01","0703282040-02")) %>% select(yr,om,st,ns,sn,sg,mag,inj,fat,loss,slat,slon,elat,elon,len),10))
t$base <- sub("-[0-9]+$","",t$om)
cat("sg==1 rows with dash in om:", sum(t$sg==1 & grepl("-",t$om)), "\n")
b1 <- t %>% filter(sg==1) %>% mutate(bid=paste(yr,base,sep="_"))
segonly <- t %>% filter(!id %in% (t %>% filter(sg==1) %>% pull(id)), sg!=-9)
cat("segment-only ids (excl sg -9):", n_distinct(segonly$id), "\n")
segonly$bid <- paste(segonly$yr, segonly$base, sep="_")
cat(" of which a whole-track sg==1 row exists under the base om:", n_distinct(segonly$id[segonly$bid %in% b1$bid]), "\n")
cat(" segment-only ids with mag>=1:", n_distinct(segonly$id[segonly$mag>=1]), "\n")
cat(" segment-only by year:\n"); print(table(segonly$yr[!duplicated(segonly$id)]))
print(table(segonly$sg, segonly$ns))
